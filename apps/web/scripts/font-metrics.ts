import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { cardFonts } from "../site/fonts.ts";

const ranges: [number, number][] = [
  [0x20, 0x7e],
  [0xa0, 0x24f],
  [0x2010, 0x2027],
];

const fontDirectory = path.join(import.meta.dirname, "../fonts");
const output = path.join(import.meta.dirname, "../site/font-metrics.ts");

type Glyph = [advance: number, xMin: number, xMax: number, yMin: number, yMax: number] | [advance: number];

export function readMetrics(bytes: Uint8Array) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const tables = new Map<string, number>();
  for (let index = 0, count = view.getUint16(4); index < count; index++) {
    const record = 12 + index * 16;
    const tag = String.fromCharCode(...bytes.subarray(record, record + 4));
    tables.set(tag, view.getUint32(record + 8));
  }
  const table = (tag: string) => {
    const offset = tables.get(tag);
    if (offset === undefined) throw new Error(`The font has no ${tag} table`);
    return offset;
  };
  const head = table("head");
  const unitsPerEm = view.getUint16(head + 18);
  const hhea = table("hhea");
  const ascender = view.getInt16(hhea + 4);
  const descender = view.getInt16(hhea + 6);
  const longOffsets = view.getInt16(head + 50) === 1;
  const glyphCount = view.getUint16(table("maxp") + 4);
  const metricCount = view.getUint16(hhea + 34);
  const hmtx = table("hmtx");
  const loca = table("loca");
  const glyf = table("glyf");

  const advance = (glyph: number) => view.getUint16(hmtx + Math.min(glyph, metricCount - 1) * 4);
  const glyphOffset = (glyph: number) => (longOffsets ? view.getUint32(loca + glyph * 4) : view.getUint16(loca + glyph * 2) * 2);
  const describe = (glyph: number): Glyph => {
    const start = glyphOffset(glyph);
    if (glyphOffset(glyph + 1) === start) return [advance(glyph)];
    const at = glyf + start;
    return [advance(glyph), view.getInt16(at + 2), view.getInt16(at + 6), view.getInt16(at + 4), view.getInt16(at + 8)];
  };

  const cmap = table("cmap");
  let subtable: number | undefined;
  for (let index = 0, count = view.getUint16(cmap + 2); index < count; index++) {
    const record = cmap + 4 + index * 8;
    const platform = view.getUint16(record);
    const encoding = view.getUint16(record + 2);
    const offset = cmap + view.getUint32(record + 4);
    if (view.getUint16(offset) === 4 && ((platform === 3 && encoding === 1) || platform === 0)) subtable = offset;
  }
  if (subtable === undefined) throw new Error("The font has no format 4 Unicode cmap");
  const segments = view.getUint16(subtable + 6) / 2;
  const ends = subtable + 14;
  const starts = ends + segments * 2 + 2;
  const deltas = starts + segments * 2;
  const rangeOffsets = deltas + segments * 2;
  const glyphFor = (code: number) => {
    for (let segment = 0; segment < segments; segment++) {
      if (code > view.getUint16(ends + segment * 2)) continue;
      const start = view.getUint16(starts + segment * 2);
      if (code < start) return 0;
      const delta = view.getInt16(deltas + segment * 2);
      const rangeOffset = view.getUint16(rangeOffsets + segment * 2);
      if (rangeOffset === 0) return (code + delta) & 0xffff;
      const glyph = view.getUint16(rangeOffsets + segment * 2 + rangeOffset + (code - start) * 2);
      return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
    }
    return 0;
  };

  const glyphs: Record<string, Glyph> = {};
  for (const [first, last] of ranges) {
    for (let code = first; code <= last; code++) {
      const glyph = glyphFor(code);
      if (glyph > 0 && glyph < glyphCount) glyphs[String.fromCharCode(code)] = describe(glyph);
    }
  }
  return { unitsPerEm, ascender, descender, glyphs };
}

async function render() {
  const fonts = await Promise.all(
    Object.entries(cardFonts).map(async ([name, file]) => [name, readMetrics(await readFile(path.join(fontDirectory, file)))] as const),
  );
  const body = fonts
    .map(
      ([name, { unitsPerEm, ascender, descender, glyphs }]) =>
        `  ${name}: {\n    unitsPerEm: ${unitsPerEm},\n    ascender: ${ascender},\n    descender: ${descender},\n    glyphs: ${JSON.stringify(glyphs)},\n  },`,
    )
    .join("\n");
  return `// Generated by scripts/font-metrics.ts from apps/web/fonts; do not edit. Units are the font's (per em).
// Each glyph is [advance, xMin, xMax, yMin, yMax], or [advance] when it has no ink.
export const fontMetrics: Record<"${Object.keys(cardFonts).join('" | "')}", { unitsPerEm: number; ascender: number; descender: number; glyphs: Record<string, readonly number[]> }> = {
${body}
};
`;
}

if (import.meta.main) {
  const generated = await render();
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== generated) {
      console.error("site/font-metrics.ts is out of date: run `bun scripts/font-metrics.ts`");
      process.exit(1);
    }
  } else {
    await writeFile(output, generated);
  }
}

export { render as renderFontMetrics };
